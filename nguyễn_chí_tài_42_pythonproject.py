import streamlit as st
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

# 1. Hiển thị tiêu đề: QUẢN LÝ ĐIỂM SINH VIÊN
st.title("QUẢN LÝ ĐIỂM SINH VIÊN")

# Khởi tạo dữ liệu 10 sinh viên
data = {
    "Họ tên": ["An", "Bình", "Chi", "Dũng", "Hà", "Lan", "Minh", "Nam", "Phúc", "Trang"],
    "Chuyên cần": [8.0, 9.0, 7.0, 8.5, 8.0, 6.0, 9.0, 7.5, 8.0, 9.5],
    "Giữa kỳ": [7.5, 8.0, 6.5, 9.0, 7.0, 5.5, 8.5, 7.0, 7.5, 9.0],
    "Cuối kỳ": [7.0, 8.5, 6.0, 9.0, 7.5, 5.0, 8.5, 6.5, 7.0, 9.5]
}

df = pd.DataFrame(data)

# Tính điểm tổng kết (Công thức: 20% Chuyên cần + 30% Giữa kỳ + 50% Cuối kỳ)
df["Tổng kết"] = (0.2 * df["Chuyên cần"] + 0.3 * df["Giữa kỳ"] + 0.5 * df["Cuối kỳ"]).round(2)

# Hàm xếp loại
def xep_loai(diem):
    if diem >= 8.5:
        return "Xuất sắc"
    elif diem >= 7.0:
        return "Giỏi"
    elif diem >= 5.5:
        return "Khá"
    elif diem >= 4.0:
        return "Trung bình"
    else:
        return "Yếu"

df["Xếp loại"] = df["Tổng kết"].apply(xep_loai)

# 2. Hiển thị bảng điểm của 10 sinh viên gồm: Họ tên, Chuyên cần, Giữa kỳ, Cuối kỳ, Tổng kết và Xếp loại.
st.subheader("Bảng điểm sinh viên")
st.dataframe(df)

# Các chỉ số thống kê
st.subheader("Thống kê chung")

# 3. Hiển thị điểm trung bình của lớp.
dtb_lop = df["Tổng kết"].mean()
st.write(f"- **Điểm trung bình của lớp:** {dtb_lop:.2f}")

# 4. Hiển thị sinh viên có điểm tổng kết cao nhất và thấp nhất.
sv_cao_nhat = df.loc[df["Tổng kết"].idxmax()]
sv_thap_nhat = df.loc[df["Tổng kết"].idxmin()]
st.write(f"- **Sinh viên điểm cao nhất:** {sv_cao_nhat['Họ tên']} ({sv_cao_nhat['Tổng kết']} điểm)")
st.write(f"- **Sinh viên điểm thấp nhất:** {sv_thap_nhat['Họ tên']} ({sv_thap_nhat['Tổng kết']} điểm)")

# 5. Hiển thị số sinh viên đạt. (Điểm tổng kết >= 4.0)
so_sv_dat = (df["Tổng kết"] >= 4.0).sum()
st.write(f"- **Số sinh viên đạt:** {so_sv_dat}/{len(df)} sinh viên")

st.markdown("---")

# 6. Tạo danh sách xổ xuống (Selectbox) để người dùng chọn một sinh viên.
st.subheader("Tra cứu thông tin sinh viên")
selected_student = st.selectbox("Chọn một sinh viên:", df["Họ tên"])

# 7. Khi chọn sinh viên, hiển thị điểm Chuyên cần, Giữa kỳ, Cuối kỳ, Điểm tổng kết và Xếp loại của sinh viên đó.
student_info = df[df["Họ tên"] == selected_student].iloc[0]
st.write(f"**Thông tin chi tiết của {selected_student}:**")
st.write(f"- Chuyên cần: {student_info['Chuyên cần']}")
st.write(f"- Giữa kỳ: {student_info['Giữa kỳ']}")
st.write(f"- Cuối kỳ: {student_info['Cuối kỳ']}")
st.write(f"- Điểm tổng kết: {student_info['Tổng kết']}")
st.write(f"- Xếp loại: {student_info['Xếp loại']}")

st.markdown("---")

# 8. Hiển thị biểu đồ cột điểm tổng kết của 10 sinh viên.
st.subheader("Biểu đồ điểm tổng kết")
fig, ax = plt.subplots(figsize=(8, 4))
ax.bar(df["Họ tên"], df["Tổng kết"], color="skyblue")
ax.set_xlabel("Họ tên sinh viên")
ax.set_ylabel("Điểm tổng kết")
ax.set_title("Biểu đồ cột điểm tổng kết của 10 sinh viên")
ax.set_ylim(0, 10)
for index, value in enumerate(df["Tổng kết"]):
    ax.text(index, value + 0.1, str(value), ha='center')

st.pyplot(fig)

st.markdown("---")

