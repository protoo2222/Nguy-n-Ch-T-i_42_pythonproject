import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import streamlit as st
# 1. Tạo DataFrame và Tính toán
data = {"Họ tên": ["An", "Bình","Chi","Dũng", "Hà", "Lan", "Minh", "Nam","Phúc","Trang",],
        "Chuyên cần": [8.0, 9.0, 7.0, 8.5, 8.0, 6.0, 9.0, 7.5, 8.0, 9.5],
        "Giữa kỳ": [7.5, 8.0, 6.5, 9.0, 7.0, 5.5, 8.5, 7.0, 7.5, 9.0],
        "Cuối kỳ": [7.0, 8.5, 6.0, 9.0, 7.5, 5.0, 8.5, 6.5, 7.0, 9.5],}
# 2. Tạo DataFrame
df = pd.DataFrame(data)
# 3. Hiển thị bảng dữ liệu
st.dataframe(df)
df = pd.DataFrame(data)

# 4. Tính điểm tổng kết theo công thức
df["Tong_ket"] = ( 0.2 * df["Chuyên cần"] + 0.3 * df["Giữa kỳ"]+ 0.5 * df["Cuối kỳ"])
# 5. Hiển thị bảng dữ liệu sau khi đã thêm cột Tổng kết
st.write("BẢNG DỮ LIỆU SAU KHI TÍNH ĐIỂM TỔNG KẾT:")
st.dataframe(df)
# 5. Tạo hàm xếp loại sinh viên:
def phan_loai(diem):
  if diem >= 8.5:
    return "Giỏi"
  elif diem >= 7.0:
    return "Khá"
  elif diem >= 5.0:
    return "Trung bình"
  else:
    return "Yếu"
# 6. Áp dụng hàm để tạo thêm cột Xep_loai
df["Xep_loai"] = df["Tong_ket"].apply(phan_loai)
# Hiển thị bảng kết quả
st.write("BẢNG DỮ LIỆU SAU KHI XẾP LOẠI:")
st.dataframe(df)
# 7. Tính điểm tổng kết trung bình của lớp
diem_tb_lop = df["Tong_ket"].mean()
st.write(f"- Điểm tổng kết trung bình của lớp: {diem_tb_lop:.2f}")
# 8. Tìm sinh viên có điểm tổng kết cao nhất
max_idx = df["Tong_ket"].idxmax()
sv_max = df.loc[max_idx, "Họ tên"]
diem_max = df.loc[max_idx, "Tong_ket"]
st.write(f"- Sinh viên có điểm tổng kết cao nhất: {sv_max} với {diem_max} điểm")
# 9. Tìm sinh viên có điểm tổng kết thấp nhất
min_idx = df["Tong_ket"].idxmin()
sv_min = df.loc[min_idx, "Họ tên"]
diem_min = df.loc[min_idx, "Tong_ket"]
st.write(f"- Sinh viên có điểm tổng kết thấp nhất: {sv_min} với {diem_min} điểm")
# 10. Đếm số sinh viên đạt (điểm tổng kết >= 5.0)
so_sv_dat = (df["Tong_ket"] >= 5.0).sum()
st.write(f"- Số sinh viên đạt (Tổng kết >= 5.0): {so_sv_dat} / {len(df)}")
plt.figure(figsize=(9, 5))

# 11. Vẽ biểu đồ cột ngang (giống với mẫu hình ảnh hướng dẫn)
plt.barh(df["Họ tên"], df["Tong_ket"], color="#4A90E2")

# Thiết lập tiêu đề và nhãn các trục[cite: 2]
plt.xlabel("Điểm tổng kết", fontsize=12)
plt.ylabel("Sinh viên", fontsize=12)
plt.title(
    "BIỂU ĐỒ THỂ HIỆN ĐIỂM TỔNG KẾT CỦA 10 SINH VIÊN",
    fontsize=14,
    fontweight="bold",
)

# Giới hạn trục điểm từ 0 đến 10
plt.xlim(0, 10)

# Hiển thị giá trị điểm cụ thể cạnh mỗi cột để dễ quan sát
for index, value in enumerate(df["Tong_ket"]):
  plt.text(value + 0.1, index, str(value), va="center", fontsize=10)

# Tinh chỉnh bố cục và hiển thị biểu đồ
plt.tight_layout()
st.pyplot(plt.gcf())